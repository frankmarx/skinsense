import datetime
import uuid
from chalicelib.db import SessionLocal
from chalicelib.models.common.job_log_details import JobLogDetails
from chalicelib.models.common.event_log_details import EventLogDetails


class EventLogger:
    """Unified logger for the event and job lifecycle.

    An EventLogger is created either for a NEW event (passing ``event_type``
    and ``source``) or for an EXISTING event (passing ``event_id``, which is
    looked up in the database). New events get a freshly generated UUID that
    is saved to the object until ``create_event()`` persists it.

    Lifecycle:
        EventLogger(event_type, source) -> create_event() -> finish_event()
        EventLogger(event_id) -> create_job(action) -> finish_job(job_id, success)
    """

    def __init__(self, event_id=None, event_type=None, source=None):
        """Initialize the logger for a new or existing event.

        Args:
            event_id (str): ID of an existing event to attach to. When
                provided, ``event_type`` and ``source`` must be omitted; the
                rest of the event's information is loaded from the database.
            event_type (str): Type of a new event (e.g. 'cs_float_test_connection').
                Required (with ``source``) when ``event_id`` is omitted.
            source (str): Origin of a new event ('scheduled' or 'custom').
                Required (with ``event_type``) when ``event_id`` is omitted.

        Returns:
            None. A UUID is generated for new events and stored on the object.

        Raises:
            ValueError: If the arguments do not match one of the two valid
                constructor modes, or if ``event_id`` does not exist in
                event_log_details.
        """
        if event_id is not None:
            if event_type is not None or source is not None:
                raise ValueError(
                    "Invalid EventLogger arguments: pass either event_id alone "
                    "to attach to an existing event, or event_type and source "
                    "to create a new one, not a combination of both."
                )
            with SessionLocal() as db:
                event = db.query(EventLogDetails).filter(
                    EventLogDetails.event_id == event_id
                ).first()
            if not event:
                raise ValueError(
                    f"Event '{event_id}' not found in event_log_details. "
                    "Only existing event IDs may be passed to EventLogger."
                )
            self.event_id = event.event_id
            self.event_type = event.event_type
            self.source = event.source
        else:
            if not event_type or not source:
                raise ValueError(
                    "Invalid EventLogger arguments: a new event requires both "
                    "event_type and source."
                )
            self.event_id = str(uuid.uuid4())
            self.event_type = event_type
            self.source = source

    def create_event(self):
        """Persist the event to event_log_details.

        Inserts a row for the event using the ID generated at construction,
        stamping the start time. The event's end time remains unset until
        ``finish_event()`` is called.

        Returns:
            str: The event ID.

        Raises:
            RuntimeError: If an event with this ID already exists in
                event_log_details. IDs are UUIDs generated by this class, so
                a collision should never occur; seeing this error indicates
                a duplicate or buggy call.
        """
        with SessionLocal() as db:
            existing = db.query(EventLogDetails).filter(
                EventLogDetails.event_id == self.event_id
            ).first()
            if existing:
                raise RuntimeError(
                    f"Cannot create event '{self.event_id}': an event with "
                    "this ID already exists in event_log_details."
                )
            log = EventLogDetails(
                event_id=self.event_id,
                event_type=self.event_type,
                source=self.source,
                start_time=datetime.datetime.now()
            )
            db.add(log)
            db.commit()
        return self.event_id

    def finish_event(self):
        """Stamp the end time on the event, closing it out.

        Raises:
            RuntimeError: If the event does not exist in event_log_details,
                or if it already has an end time (i.e. ``finish_event()`` was
                already called). Each event may only be finished once.
        """
        with SessionLocal() as db:
            event = db.query(EventLogDetails).filter(
                EventLogDetails.event_id == self.event_id
            ).first()
            if not event:
                raise RuntimeError(
                    f"Cannot finish event '{self.event_id}': event not found "
                    "in event_log_details. Call create_event() first."
                )
            if event.end_time is not None:
                raise RuntimeError(
                    f"Cannot finish event '{self.event_id}': the event already "
                    f"has an end time ({event.end_time.isoformat()})."
                )
            event.end_time = datetime.datetime.now()
            db.commit()

    def create_job(self, action):
        """Create a job under this event and mark it as running.

        Generates a new job ID, verifies no other job is currently in
        progress for this event, and inserts a job_log_details row with
        status 'Running'. Jobs for a single event never run in parallel.

        Args:
            action (str): Description of the work the job performs
                (e.g. 'Testing Connection').

        Returns:
            str: The newly generated job ID.

        Raises:
            RuntimeError: If the event does not exist in event_log_details
                (call ``create_event()`` first), or if the event already has
                a job in progress (a row with a start time and no end time).
        """
        with SessionLocal() as db:
            event = db.query(EventLogDetails).filter(
                EventLogDetails.event_id == self.event_id
            ).first()
            if not event:
                raise RuntimeError(
                    f"Cannot create job for event '{self.event_id}': the event "
                    "does not exist in event_log_details. Call create_event() first."
                )
            in_progress = db.query(JobLogDetails).filter(
                JobLogDetails.event_id == self.event_id,
                JobLogDetails.end_time.is_(None)
            ).first()
            if in_progress:
                raise RuntimeError(
                    f"Cannot create job for event '{self.event_id}': job "
                    f"'{in_progress.job_id}' ({in_progress.action}) is still "
                    "in progress. Jobs for the same event may not run in parallel."
                )
            job_id = str(uuid.uuid4())
            log = JobLogDetails(
                job_id=job_id,
                event_id=self.event_id,
                action=action,
                status='Running',
                start_time=datetime.datetime.now()
            )
            db.add(log)
            db.commit()
        return job_id

    def finish_job(self, job_id, success):
        """Mark a job as Completed or Failed and stamp its end time.

        Args:
            job_id (str): ID of the job to finish, as returned by
                ``create_job()``.
            success (bool): True marks the job 'Completed'; False marks it
                'Failed'.

        Returns:
            None.

        Raises:
            RuntimeError: If no job with this ID exists in job_log_details,
                or if the job is already finished (has an end time). Each job
                may only be finished once.
        """
        final_status = 'Completed' if success else 'Failed'
        with SessionLocal() as db:
            job = db.query(JobLogDetails).filter(
                JobLogDetails.job_id == job_id
            ).first()
            if not job:
                raise RuntimeError(
                    f"Cannot finish job '{job_id}': job not found in "
                    "job_log_details."
                )
            if job.end_time is not None:
                raise RuntimeError(
                    f"Cannot finish job '{job_id}': the job is already "
                    f"finished with status '{job.status}'."
                )
            job.status = final_status
            job.end_time = datetime.datetime.now()
            db.commit()
